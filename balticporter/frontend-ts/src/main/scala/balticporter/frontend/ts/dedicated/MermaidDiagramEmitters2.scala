    sb.append("final case class ClassRelation(\n")
    sb.append("  from:            String,\n")
    sb.append("  to:              String,\n")
    sb.append("  relType:         String = \"\",\n")
    sb.append("  label:           String = \"\",\n")
    sb.append("  fromCardinality: String = \"\",\n")
    sb.append("  toCardinality:   String = \"\"\n")
    sb.append(")\n\n")

    sb.append("final class ClassDiagramDb {\n\n")
    sb.append("  val classes:    mutable.LinkedHashMap[String, ClassNode] = mutable.LinkedHashMap.empty\n")
    sb.append("  val relations:  mutable.ArrayBuffer[ClassRelation]       = mutable.ArrayBuffer.empty\n")
    sb.append("  val namespaces: mutable.ArrayBuffer[String]              = mutable.ArrayBuffer.empty\n\n")
    sb.append("  var direction:      String = \"TB\"\n")
    sb.append("  var title:          String = \"\"\n")
    sb.append("  var accTitle:       String = \"\"\n")
    sb.append("  var accDescription: String = \"\"\n\n")
    sb.append("  def addClass(id: String, label: String = \"\"): Unit =\n")
    sb.append("    classes.getOrElseUpdate(id, ClassNode(id = id, label = if (label.nonEmpty) label else id))\n\n")
    sb.append("  def addRelation(from: String, to: String, relType: String = \"\", label: String = \"\"): Unit = {\n")
    sb.append("    addClass(from); addClass(to)\n")
    sb.append("    relations += ClassRelation(from = from, to = to, relType = relType, label = label)\n")
    sb.append("  }\n\n")
    sb.append("  def addAnnotation(className: String, annotation: String): Unit =\n")
    sb.append("    classes.get(className).foreach(_.annotations += annotation)\n\n")
    sb.append("  def clear(): Unit = {\n")
    sb.append("    classes.clear(); relations.clear(); namespaces.clear()\n")
    sb.append("    direction = \"TB\"; title = \"\"; accTitle = \"\"; accDescription = \"\"\n")
    sb.append("  }\n")
    sb.append("}\n")
