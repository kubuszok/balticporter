    sb.append(")\n\n")

    sb.append("final case class ClassNode(\n")
    sb.append("  id:          String,\n")
    sb.append("  label:       String = \"\",\n")
    sb.append("  members:     mutable.ArrayBuffer[ClassMember] = mutable.ArrayBuffer.empty,\n")
    sb.append("  annotations: mutable.ArrayBuffer[String]      = mutable.ArrayBuffer.empty,\n")
    sb.append("  isInterface: Boolean = false,\n")
    sb.append("  namespace:   String = \"\"\n")
