    sb.append("  def render(db: ClassDiagramDb, config: MermaidConfig): String = {\n")
    sb.append("    val viewBox = \"0 0 800 600\"\n")
    sb.append("    val svg     = SvgBuilder.createSvg(viewBox)\n")
    sb.append("    svg.attr(\"role\", \"img\"); svg.classed(\"mermaid\", true)\n")
    sb.append("    Accessibility.applyTo(svg, \"class\", db.accTitle, db.accDescription)\n\n")
    sb.append("    val defs      = svg.append(\"defs\")\n")
    sb.append("    val themeVars = Theme.getThemeByName(config.theme, config.themeVariables)\n")
    sb.append("    val css       = ClassStyles.generate(themeVars)\n")
    sb.append("    val baseCss   = CssGenerator.generateBaseStyles(themeVars)\n")
    sb.append("    val styleEl   = defs.append(\"style\")\n")
    sb.append("    styleEl.attr(\"type\", \"text/css\")\n")
    sb.append("    styleEl.text(baseCss + \"\\n\" + css + (if (config.themeCSS.nonEmpty) \"\\n\" + config.themeCSS else \"\"))\n\n")
    sb.append("    val mainGroup = svg.append(\"g\")\n")
    sb.append("    if (db.title.nonEmpty) {\n")
    sb.append("      mainGroup.append(\"text\").classed(\"classTitle\", true).text(db.title)\n")
    sb.append("    }\n")
    sb.append("    for ((id, cls) <- db.classes) {\n")
    sb.append("      val g = mainGroup.append(\"g\").classed(\"classBox\", true)\n")
    sb.append("      g.append(\"rect\")\n")
    sb.append("      g.append(\"text\").classed(\"classLabel\", true).text(cls.label)\n")
    sb.append("      for (ann <- cls.annotations) {\n")
    sb.append("        g.append(\"text\").classed(\"classAnnotation\", true).text(s\"<<$ann>>\")\n")
    sb.append("      }\n")
    sb.append("      for (member <- cls.members) {\n")
    sb.append("        g.append(\"text\").classed(\"classMember\", true).text(member.name)\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    for (rel <- db.relations) {\n")
    sb.append("      mainGroup.append(\"path\").classed(\"classRelation\", true)\n")
    sb.append("    }\n\n")
    sb.append("    svg.build().toMarkup()\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

