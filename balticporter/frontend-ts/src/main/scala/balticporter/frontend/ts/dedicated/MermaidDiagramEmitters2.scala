    sb.append("  def addMessage(from: String, to: String, label: String = \"\", msgType: Int = 0): Unit =\n")
    sb.append("    messages += SeqMessage(from = from, to = to, label = label, msgType = msgType)\n\n")
    sb.append("  def addNote(text: String, placement: String = \"over\", actors: Seq[String] = Seq.empty): Unit =\n")
