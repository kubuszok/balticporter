    sb.append("  def addLoop(label: String): Unit =\n")
    sb.append("    loops += SeqLoop(label = label)\n\n")
    sb.append("  def clear(): Unit = {\n")
    sb.append("    actors.clear(); messages.clear(); notes.clear(); loops.clear()\n")
    sb.append("    autoNumber = false; title = \"\"; accTitle = \"\"; accDescription = \"\"\n")
    sb.append("  }\n")
