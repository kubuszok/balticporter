  def emitErParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "ErParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage er\n\n")
    sb.append("import ssg.mermaid.parse.{ ParseException, Scanner }\n\n")
    sb.append("import scala.util.boundary\nimport scala.util.boundary.break\n\n")
    sb.append("object ErParser {\n\n")
    sb.append("  def parse(input: String): ErDb = parse(input, new ErDb)\n\n")
    sb.append("  def parse(input: String, db: ErDb): ErDb = {\n")
    sb.append("    val cleaned = input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\").replaceAll(\"%%[^\\n]*\", \"\")\n")
    sb.append("    val scanner = new Scanner(cleaned)\n")
    sb.append("    scanner.skipWhitespaceAndNewlines()\n")
    sb.append("    if (!scanner.matchStrIgnoreCase(\"erDiagram\"))\n")
    sb.append("      throw new ParseException(\"Expected 'erDiagram' keyword\", scanner.line, scanner.col)\n")
    sb.append("    parseBody(scanner, db)\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def parseBody(scanner: Scanner, db: ErDb): Unit = boundary {\n")
    sb.append("    while (!scanner.isEof) {\n")
    sb.append("      scanner.skipWhitespaceAndNewlines()\n")
    sb.append("      if (scanner.isEof) break()\n")
    sb.append("      skipToNewline(scanner)\n")
    sb.append("    }\n")
    sb.append("  }\n\n")
    sb.append("  private def skipToNewline(scanner: Scanner): Unit = {\n")
    sb.append("    while (!scanner.isEof && scanner.peek() != '\\n') scanner.advance()\n")
    sb.append("    if (!scanner.isEof) scanner.advance()\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

  def emitErRenderer(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "ErRenderer.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage er\n\n")
    sb.append("import ssg.mermaid.Accessibility\nimport ssg.mermaid.MermaidConfig\n")
    sb.append("import ssg.graphs.commons.svg.SvgBuilder\n")
    sb.append("import ssg.mermaid.theme.{ CssGenerator, Theme }\n\n")
    sb.append("object ErRenderer {\n\n")
    sb.append("  def render(db: ErDb, config: MermaidConfig): String = {\n")
    sb.append("    val viewBox = \"0 0 800 600\"\n")
    sb.append("    val svg     = SvgBuilder.createSvg(viewBox)\n")
    sb.append("    svg.attr(\"role\", \"img\"); svg.classed(\"mermaid\", true)\n")
    sb.append("    Accessibility.applyTo(svg, \"er\", db.accTitle, db.accDescription)\n\n")
    sb.append("    val defs      = svg.append(\"defs\")\n")
    sb.append("    val themeVars = Theme.getThemeByName(config.theme, config.themeVariables)\n")
    sb.append("    val css       = ErStyles.generate(themeVars)\n")
    sb.append("    val baseCss   = CssGenerator.generateBaseStyles(themeVars)\n")
    sb.append("    val styleEl   = defs.append(\"style\")\n")
    sb.append("    styleEl.attr(\"type\", \"text/css\")\n")
    sb.append("    styleEl.text(baseCss + \"\\n\" + css + (if (config.themeCSS.nonEmpty) \"\\n\" + config.themeCSS else \"\"))\n\n")
    sb.append("    val mainGroup = svg.append(\"g\")\n")
    sb.append("    if (db.title.nonEmpty) {\n")
    sb.append("      mainGroup.append(\"text\").attr(\"x\", 400).attr(\"y\", 25).attr(\"text-anchor\", \"middle\").classed(\"er-title\", true).text(db.title)\n")
    sb.append("    }\n\n")
    sb.append("    var yOff = 50\n")
    sb.append("    for ((name, entity) <- db.entities) {\n")
    sb.append("      val g = mainGroup.append(\"g\").classed(\"entityBox\", true)\n")
    sb.append("      g.append(\"rect\").attr(\"x\", 20).attr(\"y\", yOff).attr(\"width\", 200).attr(\"height\", 40 + entity.attributes.size * 20)\n")
    sb.append("      g.append(\"text\").attr(\"x\", 120).attr(\"y\", yOff + 25).attr(\"text-anchor\", \"middle\").classed(\"entityLabel\", true).text(name)\n")
    sb.append("      yOff += 60 + entity.attributes.size * 20\n")
    sb.append("    }\n\n")
    sb.append("    for (rel <- db.relationships) {\n")
    sb.append("      mainGroup.append(\"line\").classed(\"relationshipLine\", true)\n")
    sb.append("      mainGroup.append(\"text\").classed(\"relationshipLabel\", true).text(rel.label)\n")
    sb.append("    }\n\n")
    sb.append("    svg.build().toMarkup()\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

