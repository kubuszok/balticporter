  def emitEventModelingParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "EventModelingParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage eventmodeling\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("/** Hand-written parser for Mermaid event modeling syntax. */\n")
    sb.append("object EventModelingParser {\n\n")
    sb.append("  def parse(input: String): EventModelingDb = parse(input, new EventModelingDb)\n\n")
    sb.append("  def parse(input: String, db: EventModelingDb): EventModelingDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"eventmodeling\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'eventmodeling' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val line    = lines(i); val trimmed = line.trim; i += 1\n")
    sb.append("      if (trimmed.isEmpty || trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"lane \")) {\n")
    sb.append("        db.addLane(trimmed.substring(5).trim)\n")
    sb.append("      } else if (trimmed.contains(\"-->\")) {\n")
    sb.append("        val parts = trimmed.split(\"-->\")\n")
    sb.append("        if (parts.length >= 2) {\n")
    sb.append("          val fromId = parts(0).trim\n")
    sb.append("          val rest   = parts(1).trim\n")
    sb.append("          val labelIdx = rest.indexOf('[')\n")
    sb.append("          val (toId, label) = if (labelIdx >= 0) {\n")
    sb.append("            val endIdx = rest.indexOf(']', labelIdx)\n")
    sb.append(
      "            (rest.substring(0, labelIdx).trim, if (endIdx > labelIdx) rest.substring(labelIdx + 1, endIdx).trim else \"\")\n"
    )
    sb.append("          } else (rest, \"\")\n")
    sb.append("          db.addFlow(fromId, toId, label)\n")
    sb.append("        }\n")
    sb.append("      } else {\n")
    sb.append("        val (id, label, lane, eventType) = parseEvent(trimmed)\n")
    sb.append("        db.addEvent(id, label, lane, eventType)\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n\n")
    sb.append("  private def parseEvent(text: String): (String, String, String, String) = {\n")
    sb.append("    // Format: id[\"label\"] in lane : type\n")
    sb.append("    val bracketIdx = text.indexOf('[')\n")
    sb.append("    if (bracketIdx >= 0) {\n")
    sb.append("      val id     = text.substring(0, bracketIdx).trim\n")
    sb.append("      val endIdx = text.indexOf(']', bracketIdx)\n")
    sb.append(
      "      val label  = if (endIdx > bracketIdx) text.substring(bracketIdx + 1, endIdx).trim.stripPrefix(\"\\\"\").stripSuffix(\"\\\"\") else id\n"
    )
    sb.append("      val rest   = if (endIdx > 0) text.substring(endIdx + 1).trim else \"\"\n")
    sb.append("      val inIdx  = rest.toLowerCase.indexOf(\"in \")\n")
    sb.append("      val (lane, eType) = if (inIdx >= 0) {\n")
    sb.append("        val afterIn   = rest.substring(inIdx + 3).trim\n")
    sb.append("        val colonIdx  = afterIn.indexOf(':')\n")
    sb.append("        if (colonIdx >= 0) (afterIn.substring(0, colonIdx).trim, afterIn.substring(colonIdx + 1).trim)\n")
    sb.append("        else (afterIn, \"event\")\n")
    sb.append("      } else (\"default\", \"event\")\n")
    sb.append("      (id, label, lane, eType)\n")
    sb.append("    } else (text, text, \"default\", \"event\")\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

  def emitEventModelingRenderer(rast: RastFile): String = {
