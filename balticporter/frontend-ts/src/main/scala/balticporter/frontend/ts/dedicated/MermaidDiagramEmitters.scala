  def emitJourneyParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "JourneyParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage journey\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("/** Hand-written parser for Mermaid user journey syntax. */\n")
    sb.append("object JourneyParser {\n\n")
    sb.append("  def parse(input: String): JourneyDb = parse(input, new JourneyDb)\n\n")
    sb.append("  def parse(input: String, db: JourneyDb): JourneyDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"journey\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'journey' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val trimmed = lines(i).trim; i += 1\n")
    sb.append("      if (trimmed.isEmpty || trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"title \")) {\n")
    sb.append("        db.title = trimmed.substring(6).trim\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"section \")) {\n")
    sb.append("        db.addSection(trimmed.substring(8).trim)\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"acctitle:\")) {\n")
    sb.append("        db.accTitle = trimmed.substring(9).trim\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"accdescr:\")) {\n")
    sb.append("        db.accDescription = trimmed.substring(9).trim\n")
    sb.append("      } else {\n")
    sb.append("        parseTask(trimmed, db)\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n\n")
    sb.append("  private def parseTask(text: String, db: JourneyDb): Unit = {\n")
    sb.append("    // Format: TaskName: score: actor1, actor2\n")
    sb.append("    val parts = text.split(\":\")\n")
    sb.append("    if (parts.length >= 2) {\n")
    sb.append("      val name  = parts(0).trim\n")
    sb.append("      val score = try { parts(1).trim.toInt } catch { case _: NumberFormatException => 3 }\n")
    sb.append("      val taskActors = if (parts.length >= 3) parts(2).split(\",\").map(_.trim) else Array.empty[String]\n")
    sb.append("      db.addTask(name, score, taskActors)\n")
    sb.append("    }\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

