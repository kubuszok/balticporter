  def emitRadarParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "RadarParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage radar\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("/** Hand-written parser for Mermaid radar chart syntax. */\n")
    sb.append("object RadarParser {\n\n")
    sb.append("  def parse(input: String): RadarDb = parse(input, new RadarDb)\n\n")
    sb.append("  def parse(input: String, db: RadarDb): RadarDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"radar-beta\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'radar-beta' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    var currentSeries: RadarSeries = null\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val trimmed = lines(i).trim; i += 1\n")
    sb.append("      if (trimmed.isEmpty || trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"title \")) {\n")
    sb.append("        db.title = trimmed.substring(6).trim\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"axis \")) {\n")
    sb.append("        val axisNames = trimmed.substring(5).split(\",\").map(_.trim).filter(_.nonEmpty)\n")
    sb.append("        axisNames.foreach(db.addAxis)\n")
    sb.append("      } else {\n")
    sb.append("        val colonIdx = trimmed.indexOf(':')\n")
    sb.append("        if (colonIdx >= 0) {\n")
    sb.append("          val name   = trimmed.substring(0, colonIdx).trim\n")
    sb.append("          val values = trimmed.substring(colonIdx + 1).split(\",\").map(_.trim).filter(_.nonEmpty)\n")
    sb.append("          val s = db.addSeries(name)\n")
    sb.append("          values.foreach(v => try { s.values += v.toDouble } catch { case _: NumberFormatException => })\n")
    sb.append("          currentSeries = s\n")
    sb.append("        }\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n")
    sb.append("}\n")
    sb.toString
  }

