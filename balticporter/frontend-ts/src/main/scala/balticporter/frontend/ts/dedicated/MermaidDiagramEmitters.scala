  def emitTreemapParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "TreemapParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage treemap\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("import scala.collection.mutable\n\n")
    sb.append("/** Hand-written parser for Mermaid treemap syntax. */\n")
    sb.append("object TreemapParser {\n\n")
    sb.append("  def parse(input: String): TreemapDb =\n")
    sb.append("    parse(input, new TreemapDb)\n\n")
    sb.append("  def parse(input: String, db: TreemapDb): TreemapDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"treemap\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'treemap' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    val stack = mutable.ArrayBuffer.empty[(Int, TreemapNode)]\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val line    = lines(i); i += 1\n")
    sb.append("      val trimmed = line.trim\n")
    sb.append("      if (trimmed.isEmpty || trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip\n")
    sb.append("      } else {\n")
    sb.append("        val indent       = line.length - line.stripLeading().length\n")
    sb.append("        val (label, value) = parseLabelValue(trimmed)\n")
    sb.append("        val node         = TreemapNode(label, value)\n\n")
    sb.append("        while (stack.nonEmpty && stack.last._1 >= indent) stack.remove(stack.size - 1)\n\n")
    sb.append("        if (stack.isEmpty) {\n")
    sb.append("          db.roots += node\n")
    sb.append("        } else {\n")
    sb.append("          stack.last._2.children += node\n")
    sb.append("        }\n")
    sb.append("        stack += ((indent, node))\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n\n")
    sb.append("  private def parseLabelValue(text: String): (String, Double) = {\n")
    sb.append("    val colonIdx = text.lastIndexOf(':')\n")
    sb.append("    if (colonIdx > 0) {\n")
    sb.append("      val label = text.substring(0, colonIdx).trim\n")
    sb.append("      val valueStr = text.substring(colonIdx + 1).trim\n")
    sb.append("      try {\n")
    sb.append("        (label, valueStr.toDouble)\n")
    sb.append("      } catch {\n")
    sb.append("        case _: NumberFormatException => (text, 0.0)\n")
    sb.append("      }\n")
    sb.append("    } else (text, 0.0)\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

  def emitTreemapRenderer(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "TreemapRenderer.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage treemap\n\n")
    sb.append("import ssg.mermaid.Accessibility\n")
    sb.append("import ssg.mermaid.MermaidConfig\n")
    sb.append("import ssg.graphs.commons.svg.SvgBuilder\n")
    sb.append("import ssg.mermaid.theme.{ CssGenerator, Theme }\n\n")
    sb.append("/** Renders a treemap diagram to SVG using slice-and-dice layout. */\n")
    sb.append("object TreemapRenderer {\n\n")
    sb.append("  private val Padding: Double = 20.0\n")
    sb.append("  private val Colors: Array[String] = Array(\n")
    sb.append("    \"#4e79a7\", \"#f28e2b\", \"#e15759\", \"#76b7b2\",\n")
    sb.append("    \"#59a14f\", \"#edc949\", \"#af7aa1\", \"#ff9da7\"\n")
    sb.append("  )\n\n")
    sb.append("  def render(db: TreemapDb, config: MermaidConfig): String = {\n")
    sb.append("    val svgWidth  = 600.0\n")
    sb.append("    val svgHeight = 400.0\n")
    sb.append("    val viewBox   = s\"0 0 $svgWidth $svgHeight\"\n")
    sb.append("    val svg       = SvgBuilder.createSvg(viewBox)\n")
    sb.append("    svg.attr(\"role\", \"img\"); svg.classed(\"mermaid\", true)\n\n")
    sb.append("    Accessibility.applyTo(svg, \"treemap\", db.accTitle, db.accDescription)\n\n")
    sb.append("    val defs      = svg.append(\"defs\")\n")
    sb.append("    val themeVars = Theme.getThemeByName(config.theme, config.themeVariables)\n")
    sb.append("    val css       = TreemapStyles.generate(themeVars)\n")
    sb.append("    val baseCss   = CssGenerator.generateBaseStyles(themeVars)\n")
    sb.append("    val styleEl   = defs.append(\"style\")\n")
    sb.append("    styleEl.attr(\"type\", \"text/css\")\n")
    sb.append("    styleEl.text(baseCss + \"\\n\" + css + (if (config.themeCSS.nonEmpty) \"\\n\" + config.themeCSS else \"\"))\n\n")
    sb.append("    val mainGroup = svg.append(\"g\")\n\n")
    sb.append("    if (db.title.nonEmpty) {\n")
    sb.append(
      "      mainGroup.append(\"text\").attr(\"x\", svgWidth / 2).attr(\"y\", 20).attr(\"text-anchor\", \"middle\").classed(\"treemapTitle\", true).text(db.title)\n"
    )
    sb.append("    }\n\n")
    sb.append("    val leaves    = db.flattenLeaves\n")
    sb.append("    val totalVal  = leaves.map(_.value).sum.max(1.0)\n")
    sb.append("    val startY    = Padding + (if (db.title.nonEmpty) 20 else 0)\n")
    sb.append("    val areaW     = svgWidth - Padding * 2\n")
    sb.append("    val areaH     = svgHeight - startY - Padding\n\n")
    sb.append("    // Slice-and-dice: alternate horizontal/vertical slicing\n")
    sb.append("    var curX = Padding\n")
    sb.append("    for ((leaf, idx) <- leaves.zipWithIndex) {\n")
    sb.append("      val ratio = leaf.value / totalVal\n")
    sb.append("      val w     = areaW * ratio\n")
    sb.append("      val color = Colors(idx % Colors.length)\n")
    sb.append(
      "      mainGroup.append(\"rect\").attr(\"x\", curX).attr(\"y\", startY).attr(\"width\", w.max(2)).attr(\"height\", areaH).style(\"fill\", color).style(\"fill-opacity\", \"0.8\").style(\"stroke\", \"white\").style(\"stroke-width\", \"2\").classed(\"treemapCell\", true)\n"
    )
    sb.append("      if (w > 30) {\n")
    sb.append(
      "        mainGroup.append(\"text\").attr(\"x\", curX + w / 2).attr(\"y\", startY + areaH / 2 + 4).attr(\"text-anchor\", \"middle\").classed(\"treemapLabel\", true).text(leaf.label)\n"
    )
    sb.append("      }\n")
    sb.append("      curX += w\n")
    sb.append("    }\n\n")
    sb.append("    svg.build().toMarkup()\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

