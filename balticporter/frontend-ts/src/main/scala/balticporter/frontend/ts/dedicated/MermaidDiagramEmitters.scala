  def emitSankeyParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "SankeyParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage sankey\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("/** Hand-written parser for Mermaid sankey-beta syntax. */\n")
    sb.append("object SankeyParser {\n\n")
