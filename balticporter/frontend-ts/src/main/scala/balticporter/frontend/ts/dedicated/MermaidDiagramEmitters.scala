  def emitMindmapParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "MindmapParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage mindmap\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("import scala.collection.mutable\n\n")
    sb.append("/** Hand-written parser for Mermaid mindmap syntax. */\n")
    sb.append("object MindmapParser {\n\n")
    sb.append("  def parse(input: String): MindmapDb =\n")
    sb.append("    parse(input, new MindmapDb)\n\n")
    sb.append("  def parse(input: String, db: MindmapDb): MindmapDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"mindmap\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'mindmap' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    val stack = mutable.ArrayBuffer.empty[(Int, MindmapNode)]\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val line    = lines(i); i += 1\n")
    sb.append("      val trimmed = line.trim\n")
    sb.append("      if (trimmed.isEmpty || trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip\n")
    sb.append("      } else {\n")
    sb.append("        val indent = line.length - line.stripLeading().length\n")
    sb.append("        val label  = trimmed\n")
    sb.append("        val node   = MindmapNode(label)\n\n")
    sb.append("        while (stack.nonEmpty && stack.last._1 >= indent) stack.remove(stack.size - 1)\n\n")
    sb.append("        if (stack.isEmpty) {\n")
    sb.append("          if (db.root == null) db.root = node\n")
    sb.append("          else db.root.children += node\n")
    sb.append("        } else {\n")
    sb.append("          stack.last._2.children += node\n")
    sb.append("        }\n")
    sb.append("        stack += ((indent, node))\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n")
    sb.append("}\n")
    sb.toString
  }

