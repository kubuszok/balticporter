    sb.append("    val marker = defs.append(\"marker\")\n")
    sb.append("    marker.attr(\"id\", \"em-arrow\").attr(\"viewBox\", \"0 0 10 10\")\n")
    sb.append(
      "    marker.attr(\"refX\", 10).attr(\"refY\", 5).attr(\"markerWidth\", 6).attr(\"markerHeight\", 6).attr(\"orient\", \"auto\")\n"
    )
    sb.append("    marker.append(\"path\").attr(\"d\", \"M 0 0 L 10 5 L 0 10 z\").style(\"fill\", themeVars.lineColor)\n\n")
    sb.append("    val mainGroup = svg.append(\"g\")\n\n")
    sb.append("    if (db.title.nonEmpty) {\n")
    sb.append(
      "      mainGroup.append(\"text\").attr(\"x\", svgWidth / 2).attr(\"y\", 20).attr(\"text-anchor\", \"middle\").classed(\"emTitle\", true).text(db.title)\n"
    )
    sb.append("    }\n\n")
    sb.append("    val startY = Padding + (if (db.title.nonEmpty) 25 else 0)\n\n")
    sb.append("    // Event positions for flow arrows\n")
