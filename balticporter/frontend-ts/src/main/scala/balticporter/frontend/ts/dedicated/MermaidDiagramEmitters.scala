    sb.append("  def parse(input: String, db: SankeyDb): SankeyDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"sankey-beta\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'sankey-beta' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    // Sankey data lines are CSV-like: source, target, value\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val trimmed = lines(i).trim; i += 1\n")
    sb.append("      if (trimmed.nonEmpty && !trimmed.startsWith(\"%%\")) {\n")
    sb.append("        val parts = trimmed.split(\",\").map(_.trim)\n")
    sb.append("        if (parts.length >= 3) {\n")
    sb.append("          val source = parts(0).stripPrefix(\"\\\"\").stripSuffix(\"\\\"\")\n")
    sb.append("          val target = parts(1).stripPrefix(\"\\\"\").stripSuffix(\"\\\"\")\n")
    sb.append("          try {\n")
    sb.append("            db.addFlow(source, target, parts(2).toDouble)\n")
    sb.append("          } catch { case _: NumberFormatException => }\n")
    sb.append("        }\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n")
    sb.append("}\n")
    sb.toString
  }

