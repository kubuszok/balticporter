  def emitBlockParser(rast: RastFile): String = {
    val sb = new StringBuilder
    sb.append(header(rast.path, "BlockParser.scala"))
    sb.append("package ssg\npackage mermaid\npackage diagrams\npackage block\n\n")
    sb.append("import ssg.mermaid.parse.ParseException\n\n")
    sb.append("/** Hand-written parser for Mermaid block-beta syntax. */\n")
    sb.append("object BlockParser {\n\n")
    sb.append("  def parse(input: String): BlockDb = parse(input, new BlockDb)\n\n")
    sb.append("  def parse(input: String, db: BlockDb): BlockDb = {\n")
    sb.append("    val cleaned = cleanInput(input)\n")
    sb.append("    val lines   = cleaned.split(\"\\n\")\n\n")
    sb.append("    var i = 0\n")
    sb.append("    while (i < lines.length && !lines(i).trim.toLowerCase.startsWith(\"block-beta\")) i += 1\n")
    sb.append("    if (i >= lines.length) throw new ParseException(\"Expected 'block-beta' keyword\", 1, 1)\n")
    sb.append("    i += 1\n\n")
    sb.append("    while (i < lines.length) {\n")
    sb.append("      val trimmed = lines(i).trim; i += 1\n")
    sb.append("      if (trimmed.isEmpty) {\n")
    sb.append("        // double newline starts a new row\n")
    sb.append("        if (i < lines.length && lines(i).trim.isEmpty) { db.newRow(); i += 1 }\n")
    sb.append("      } else if (trimmed.startsWith(\"%%\")) {\n")
    sb.append("        // skip comment\n")
    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"columns \")) {\n")
    sb.append("        try { db.columns = trimmed.substring(8).trim.toInt } catch { case _: NumberFormatException => }\n")
    sb.append("      } else if (trimmed.contains(\"-->\")) {\n")
    sb.append("        val arrowIdx  = trimmed.indexOf(\"-->\")\n")
    sb.append("        val lhs       = trimmed.substring(0, arrowIdx).trim\n")
    sb.append("        val rhs       = trimmed.substring(arrowIdx + 3).trim\n")
    sb.append("        val dashIdx   = lhs.indexOf(\"--\")\n")
    sb.append("        val (from, label) = if (dashIdx >= 0) {\n")
    sb.append(
      "          (lhs.substring(0, dashIdx).trim, lhs.substring(dashIdx + 2).trim.stripPrefix(\"\\\"\").stripSuffix(\"\\\"\"))\n"
    )
    sb.append("        } else (lhs, \"\")\n")
    sb.append("        db.addEdge(from, rhs, label)\n")
    sb.append("      } else {\n")
    sb.append("        val (id, label, width) = parseBlock(trimmed)\n")
    sb.append("        db.addBlock(id, label, width)\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n\n")
    sb.append("  private def parseBlock(text: String): (String, String, Int) = {\n")
    sb.append("    val bracketIdx = text.indexOf('[')\n")
    sb.append("    val parenIdx   = text.indexOf('(')\n")
    sb.append(
      "    val openIdx    = if (bracketIdx >= 0 && parenIdx >= 0) math.min(bracketIdx, parenIdx) else if (bracketIdx >= 0) bracketIdx else parenIdx\n"
    )
    sb.append("    if (openIdx >= 0) {\n")
    sb.append("      val id    = text.substring(0, openIdx).trim\n")
    sb.append("      val close = if (text.charAt(openIdx) == '[') ']' else ')'\n")
    sb.append("      val endIdx = text.indexOf(close, openIdx)\n")
    sb.append(
      "      val label = if (endIdx > openIdx) text.substring(openIdx + 1, endIdx).trim.stripPrefix(\"\\\"\").stripSuffix(\"\\\"\") else id\n"
    )
    sb.append("      val widthIdx = text.indexOf(':', endIdx.max(0))\n")
    sb.append(
      "      val width   = if (widthIdx >= 0) try { text.substring(widthIdx + 1).trim.toInt } catch { case _: NumberFormatException => 1 } else 1\n"
    )
    sb.append("      (id, label, width)\n")
    sb.append("    } else {\n")
    sb.append("      val colonIdx = text.indexOf(':')\n")
    sb.append("      if (colonIdx >= 0) {\n")
    sb.append("        val id    = text.substring(0, colonIdx).trim\n")
    sb.append("        val width = try { text.substring(colonIdx + 1).trim.toInt } catch { case _: NumberFormatException => 1 }\n")
    sb.append("        (id, id, width)\n")
    sb.append("      } else (text, text, 1)\n")
    sb.append("    }\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

