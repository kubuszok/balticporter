    sb.append("      } else if (trimmed.toLowerCase.startsWith(\"junction \")) {\n")
    sb.append("        val rest     = trimmed.substring(9).trim\n")
    sb.append("        val inIdx    = rest.toLowerCase.indexOf(\" in \")\n")
    sb.append("        if (inIdx >= 0) db.addJunction(rest.substring(0, inIdx).trim, rest.substring(inIdx + 4).trim)\n")
    sb.append("        else db.addJunction(rest)\n")
    sb.append("      } else if (trimmed.contains(\"--\")) {\n")
    sb.append("        parseEdge(trimmed, db)\n")
    sb.append("      }\n")
    sb.append("    }\n")
    sb.append("    db\n")
    sb.append("  }\n\n")
    sb.append("  private def cleanInput(input: String): String =\n")
    sb.append("    input.replaceAll(\"%%\\\\{[^}]*\\\\}%%\", \"\")\n\n")
    sb.append("  private def splitIdLabel(text: String): (String, String) = {\n")
    sb.append("    val parenIdx = text.indexOf('(')\n")
    sb.append("    if (parenIdx >= 0) {\n")
    sb.append("      val id     = text.substring(0, parenIdx).trim\n")
    sb.append("      val endIdx = text.indexOf(')', parenIdx)\n")
    sb.append(
      "      val label  = if (endIdx > parenIdx) text.substring(parenIdx + 1, endIdx).trim else text.substring(parenIdx + 1).trim\n"
    )
    sb.append("      (id, label)\n")
    sb.append("    } else (text, text)\n")
    sb.append("  }\n\n")
    sb.append("  private def parseService(text: String, db: ArchitectureDb): Unit = {\n")
    sb.append("    val (id, label) = splitIdLabel(text)\n")
    sb.append("    val bracketIdx  = text.indexOf('[')\n")
    sb.append("    val icon        = if (bracketIdx >= 0) {\n")
    sb.append("      val endIdx    = text.indexOf(']', bracketIdx)\n")
    sb.append("      if (endIdx > bracketIdx) text.substring(bracketIdx + 1, endIdx).trim else \"\"\n")
    sb.append("    } else \"\"\n")
    sb.append("    val inIdx       = text.toLowerCase.indexOf(\" in \")\n")
    sb.append("    val group       = if (inIdx >= 0) text.substring(inIdx + 4).trim else \"\"\n")
    sb.append("    db.addService(id, label, icon, group)\n")
    sb.append("  }\n\n")
    sb.append("  private def parseEdge(text: String, db: ArchitectureDb): Unit = {\n")
    sb.append("    // Pattern: fromId:side -- label --> toId:side\n")
    sb.append("    val arrowIdx = text.indexOf(\"-->\")\n")
    sb.append("    if (arrowIdx >= 0) {\n")
    sb.append("      val lhs       = text.substring(0, arrowIdx).trim\n")
    sb.append("      val rhs       = text.substring(arrowIdx + 3).trim\n")
    sb.append("      val dashIdx   = lhs.indexOf(\"--\")\n")
    sb.append("      val (fromPart, label) = if (dashIdx >= 0) {\n")
    sb.append(
      "        (lhs.substring(0, dashIdx).trim, lhs.substring(dashIdx + 2).trim.stripPrefix(\"\\\"\").stripSuffix(\"\\\"\"))\n"
    )
    sb.append("      } else (lhs, \"\")\n")
    sb.append("      val (fromId, fromSide) = splitIdSide(fromPart)\n")
    sb.append("      val (toId, toSide)     = splitIdSide(rhs)\n")
    sb.append("      db.addEdge(fromId, toId, fromSide, toSide, label)\n")
    sb.append("    }\n")
    sb.append("  }\n\n")
    sb.append("  private def splitIdSide(text: String): (String, String) = {\n")
    sb.append("    val colonIdx = text.indexOf(':')\n")
    sb.append("    if (colonIdx >= 0) (text.substring(0, colonIdx).trim, text.substring(colonIdx + 1).trim)\n")
    sb.append("    else (text.trim, \"\")\n")
    sb.append("  }\n")
    sb.append("}\n")
    sb.toString
  }

