    sb.append("      val trimmed = lines(i).trim; i += 1\n")
    sb.append("      if (trimmed.nonEmpty && !trimmed.startsWith(\"%%\")) {\n")
    sb.append("        if (trimmed.toLowerCase.startsWith(\"title \"))         db.title = trimmed.substring(6).trim\n")
