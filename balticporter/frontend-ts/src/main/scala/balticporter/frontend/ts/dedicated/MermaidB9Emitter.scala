    sb.append("    if (colon >= 0) {\n")
    sb.append("      val label = text.substring(0, colon).trim\n")
    sb.append("      val rest  = text.substring(colon + 1).trim.split(\"[,\\\\s]+\")\n")
    sb.append("      if (rest.length >= 2) {\n")
    sb.append("        try {\n")
    sb.append("          val Array(x, y) = rest.take(2).map(_.trim)\n")
    sb.append("          db.addPoint(label, x.toDouble, y.toDouble)\n")
    sb.append("        } catch { case _: Exception => () }\n")
    sb.append("      }\n")
