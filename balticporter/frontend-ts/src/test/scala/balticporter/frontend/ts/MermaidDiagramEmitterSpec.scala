package balticporter.frontend.ts

class MermaidDiagramEmitterSpec extends munit.FunSuite:

  private def loadRast(resource: String): RastFile =
    val stream = getClass.getResourceAsStream(resource)
    assert(stream != null, s"Resource not found: $resource")
    val json = new String(stream.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8)
    stream.close()
    Rast.readFile(json)

  // -- B4: Diagram emitter tests -------------------------------------------

  test("infoDiagram.ts -> InfoDiagram from RAST"):
    val rast = loadRast("/rast/mermaid/src/diagrams/info/infoDiagram.rast.json")
    val scala = balticporter.corpus.mermaid.MermaidDiagramEmitter.emitDiagram(
      rast, "InfoDiagram", "info", "InfoDb",
      parserClass = Some("InfoParser"),
      rendererClass = Some("InfoRenderer"),
      detectorClass = Some("InfoDetector"),
    )
    assert(scala.contains("object InfoDiagram"), "should emit InfoDiagram object")
    assert(scala.contains("def detect(text: String): Boolean"), "should have detect method")
    assert(scala.contains("def parse(text: String): InfoDb"), "should have parse method")
    assert(scala.contains("def render(text: String"), "should have render method")
    assert(scala.contains("Auto-generated by MermaidDiagramEmitter"), "should have header")

