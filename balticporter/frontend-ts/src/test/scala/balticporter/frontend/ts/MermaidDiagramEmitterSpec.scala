  test("write RAST-based Diagram files to target/emitted-mermaid"):
    val outDir = java.nio.file.Path.of(sys.props.getOrElse("user.dir", ".")).resolve("target/emitted-mermaid")
    java.nio.file.Files.createDirectories(outDir)

    val files = List(
      ("/rast/mermaid/src/diagrams/info/infoDiagram.rast.json", "InfoDiagram", "info", "InfoDb"),
      ("/rast/mermaid/src/diagrams/pie/pieDiagram.rast.json", "PieDiagram", "pie", "PieDb"),
      ("/rast/mermaid/src/diagrams/sankey/sankeyDiagram.rast.json", "SankeyDiagram", "sankey", "SankeyDb"),
      ("/rast/mermaid/src/diagrams/packet/diagram.rast.json", "PacketDiagram", "packet", "PacketDb"),
      ("/rast/mermaid/src/diagrams/block/blockDiagram.rast.json", "BlockDiagram", "block", "BlockDb"),
      ("/rast/mermaid/src/diagrams/xychart/xychartDiagram.rast.json", "XyChartDiagram", "xychart", "XyChartDb"),
      ("/rast/mermaid/src/diagrams/er/erDiagram.rast.json", "ErDiagram", "er", "ErDb"),
      ("/rast/mermaid/src/diagrams/c4/c4Diagram.rast.json", "C4Diagram", "c4", "C4Db"),
      ("/rast/mermaid/src/diagrams/state/stateDiagram.rast.json", "StateDiagram", "state", "StateDb"),
      ("/rast/mermaid/src/diagrams/user-journey/journeyDiagram.rast.json", "JourneyDiagram", "journey", "JourneyDb"),
      ("/rast/mermaid/src/diagrams/timeline/timeline-definition.rast.json", "TimelineDiagram", "timeline", "TimelineDb"),
      ("/rast/mermaid/src/diagrams/requirement/requirementDiagram.rast.json", "RequirementDiagram", "requirement", "RequirementDb"),
      ("/rast/mermaid/src/diagrams/git/gitGraphDiagram.rast.json", "GitDiagram", "git", "GitDb"),
    )

    for ((rastPath, className, pkg, dbClass) <- files) {
      val rast = loadRast(rastPath)
      val scala = balticporter.corpus.mermaid.MermaidDiagramEmitter.emitDiagram(
        rast, className, pkg, dbClass,
        detectorClass = Some(className.replace("Diagram", "Detector")),
      )
      val path = outDir.resolve(s"${className}_rast.scala")
      java.nio.file.Files.writeString(path, scala)
      println(s"[emit-rast] ${className}.scala: ${scala.linesIterator.size} lines -> $path")
    }
