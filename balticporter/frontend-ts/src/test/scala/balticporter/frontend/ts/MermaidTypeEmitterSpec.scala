package balticporter.frontend.ts

class MermaidTypeEmitterSpec extends munit.FunSuite:

  private def loadRast(resource: String): RastFile =
    val stream = getClass.getResourceAsStream(resource)
    assert(stream != null, s"Resource not found: $resource")
    val json = new String(stream.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8)
    stream.close()
    Rast.readFile(json)

  // -- B3: Type emitter tests -----------------------------------------------

  test("pieTypes.ts -> case classes from RAST"):
    val rast = loadRast("/rast/mermaid/src/diagrams/pie/pieTypes.rast.json")
    val scala = balticporter.corpus.mermaid.MermaidTypeEmitter.emitTypes(rast, "", "pie")
    assert(scala.contains("package pie"), "should have correct package")
    // PieFields interface -> case class
    assert(scala.contains("case class PieFields") || scala.contains("PieFields"), "should emit PieFields")
    // PieStyleOptions interface -> case class
    assert(scala.contains("case class PieStyleOptions") || scala.contains("PieStyleOptions"),
      "should emit PieStyleOptions")
    // D3Section interface -> case class
    assert(scala.contains("case class D3Section") || scala.contains("D3Section"),
      "should emit D3Section")
    // Sections type alias
    assert(scala.contains("type Sections"), "should emit Sections type alias")
    // PieDB should be skipped (it's a method-only DB interface)
    assert(scala.contains("PieDB") && scala.contains("method declarations"),
      "should skip PieDB interface (all functions)")
    assert(scala.contains("Auto-generated by MermaidTypeEmitter"), "should have header")

  test("infoTypes.ts -> case classes from RAST"):
    val rast = loadRast("/rast/mermaid/src/diagrams/info/infoTypes.rast.json")
    val scala = balticporter.corpus.mermaid.MermaidTypeEmitter.emitTypes(rast, "", "info")
