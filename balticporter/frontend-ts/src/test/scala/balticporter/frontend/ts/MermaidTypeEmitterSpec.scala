  // -- Write all to target/emitted-mermaid ----------------------------------

  test("write RAST-based type files to target/emitted-mermaid"):
    val outDir = java.nio.file.Path.of(sys.props.getOrElse("user.dir", ".")).resolve("target/emitted-mermaid")
    java.nio.file.Files.createDirectories(outDir)

    val files = List(
      ("/rast/mermaid/src/diagrams/pie/pieTypes.rast.json", "PieTypes", "pie"),
      ("/rast/mermaid/src/diagrams/info/infoTypes.rast.json", "InfoTypes", "info"),
      ("/rast/mermaid/src/diagrams/block/blockTypes.rast.json", "BlockTypes", "block"),
      ("/rast/mermaid/src/diagrams/mindmap/mindmapTypes.rast.json", "MindmapTypes", "mindmap"),
      ("/rast/mermaid/src/diagrams/class/classTypes.rast.json", "ClassTypes", "class_"),
      ("/rast/mermaid/src/diagrams/common/commonTypes.rast.json", "CommonTypes", "common"),
      ("/rast/mermaid/src/config.type.rast.json", "ConfigTypes", ""),
      ("/rast/mermaid/src/diagrams/packet/types.rast.json", "PacketTypes", "packet"),
    )

    for ((rastPath, className, pkg) <- files) {
      val rast = loadRast(rastPath)
      val scala = balticporter.corpus.mermaid.MermaidTypeEmitter.emitTypes(rast, "", pkg)
      val path = outDir.resolve(s"${className}_rast.scala")
      java.nio.file.Files.writeString(path, scala)
      println(s"[emit-rast] ${className}.scala: ${scala.linesIterator.size} lines -> $path")
    }
