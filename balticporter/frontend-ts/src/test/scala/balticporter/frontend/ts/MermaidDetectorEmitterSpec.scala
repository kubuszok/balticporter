      ("/rast/mermaid/src/diagrams/mindmap/detector.rast.json", "MindmapDetector", "mindmap"),
      ("/rast/mermaid/src/diagrams/quadrant-chart/quadrantDetector.rast.json", "QuadrantDetector", "quadrant"),
      ("/rast/mermaid/src/diagrams/block/blockDetector.rast.json", "BlockDetector", "block"),
      ("/rast/mermaid/src/diagrams/xychart/xychartDetector.rast.json", "XyChartDetector", "xychart"),
      ("/rast/mermaid/src/diagrams/er/erDetector.rast.json", "ErDetector", "er"),
      ("/rast/mermaid/src/diagrams/c4/c4Detector.rast.json", "C4Detector", "c4"),
      ("/rast/mermaid/src/diagrams/state/stateDetector.rast.json", "StateDetector", "state"),
      ("/rast/mermaid/src/diagrams/user-journey/journeyDetector.rast.json", "JourneyDetector", "journey"),
      ("/rast/mermaid/src/diagrams/timeline/detector.rast.json", "TimelineDetector", "timeline"),
      ("/rast/mermaid/src/diagrams/requirement/requirementDetector.rast.json", "RequirementDetector", "requirement"),
      ("/rast/mermaid/src/diagrams/git/gitGraphDetector.rast.json", "GitDetector", "git")
    )

    for ((rastPath, className, pkg) <- files) {
      val rast  = loadRast(rastPath)
      val scala = balticporter.corpus.mermaid.MermaidDetectorEmitter.emitDetector(rast, className, pkg)
      val path  = outDir.resolve(s"${className}_rast.scala")
      java.nio.file.Files.writeString(path, scala)
      println(s"[emit-rast] ${className}.scala: ${scala.linesIterator.size} lines -> $path")
    }
