  test("write RAST-based Detector files to target/emitted-mermaid"):
    val outDir = java.nio.file.Path.of(sys.props.getOrElse("user.dir", ".")).resolve("target/emitted-mermaid")
    java.nio.file.Files.createDirectories(outDir)

    val files = List(
      ("/rast/mermaid/src/diagrams/info/infoDetector.rast.json", "InfoDetector", "info"),
      ("/rast/mermaid/src/diagrams/pie/pieDetector.rast.json", "PieDetector", "pie"),
